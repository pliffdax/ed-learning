#!/usr/bin/env bash
# Стартовий скрипт домашнього завдання ASG.SH.GIT.03 «Перший репозиторій з осмисленою історією».
# Створює ЗВИЧАЙНУ папку з файлами (без Git) - репозиторій ви створюєте самі.
# Запуск: bash make_homework_folder.sh [--variant-b] [ЦІЛЬОВА_ПАПКА]
#   без параметра  - основний варіант (поїздка на конференцію);
#   --variant-b    - еквівалентний варіант для повторної спроби (ремонт кухні).
# Скрипт не змінює налаштувань Git і не перезаписує наявну папку.
set -euo pipefail
variant="main"
if [ "${1:-}" = "--variant-b" ]; then variant="b"; shift; fi
target="${1:-first-repo-homework}"
if [ -e "$target" ]; then
  echo "Помилка: '$target' вже існує. Вкажіть іншу папку." >&2
  exit 1
fi
mkdir -p "$target"; cd "$target"
printf '%s\n' "$variant" > .task-variant

if [ "$variant" = "main" ]; then
  cat > plan.md <<'T'
# Поїздка на конференцію «Дані без болю»

Місто: Львів.
Дата: 13 березня 2026 (субота).
Учасників: 3.
T
  cat > budget.md <<'T'
# Бюджет (грн, навчальні числа)

Проживання: 2 ночі × 3 особи × 900 = 5400.
Разом: 5400.
T
  cat > scratch.txt <<'T'
Особисті чернетки - не для репозиторію.
Подзвонити в готель щодо раннього заїзду.
T
  cat > task.txt <<'T'
Умова (основний варіант). Повний контракт - у розділі 10 уроку SH.GIT.L01.
1. Створіть у цій папці репозиторій з гілкою main. Перший коміт - лише plan.md і budget.md у початковому вигляді.
2. У плані помилка: конференція в суботу, 14 березня 2026. Виправте рядок дати й закомітьте.
3. Додайте квитки на потяг: у план - рядок «Потяг: Київ - Львів, 14 березня о 07:10.»;
   у бюджет - рядок «Квитки: 3 × 650 = 1950.» і оновлений підсумок «Разом: 7350.». Закомітьте.
4. Закомітьте report.md (3-5 речень): як ви поділили зміни на коміти і чому.
scratch.txt не має потрапити в жоден коміт.
T
else
  cat > plan.md <<'T'
# Ремонт кухні

Початок робіт: 20 квітня 2026 (вівторок).
Майстрів: 2.
T
  cat > budget.md <<'T'
# Кошторис (грн, навчальні числа)

Плитка: 14 м² × 450 = 6300.
Разом: 6300.
T
  cat > scratch.txt <<'T'
Особисті чернетки - не для репозиторію.
Номер телефону майстра уточнити.
T
  cat > task.txt <<'T'
Умова (варіант B). Повний контракт - у розділі 10 уроку SH.GIT.L01.
1. Створіть у цій папці репозиторій з гілкою main. Перший коміт - лише plan.md і budget.md у початковому вигляді.
2. У плані помилка: роботи починаються у вівторок, 21 квітня 2026. Виправте рядок дати й закомітьте.
3. Додайте доставку плитки: у план - рядок «Доставка плитки: 18 квітня о 09:00.»;
   у кошторис - рядок «Доставка: 1200.» і оновлений підсумок «Разом: 7500.». Закомітьте.
4. Закомітьте report.md (3-5 речень): як ви поділили зміни на коміти і чому.
scratch.txt не має потрапити в жоден коміт.
T
fi
echo "Готово: папка '$target' створена (без репозиторію). Прочитайте task.txt."
